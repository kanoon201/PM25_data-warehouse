"""
สร้างตาราง dim_area (จังหวัด + อำเภอ) จากฐานข้อมูลสาธารณะ
=========================================================================
แหล่งข้อมูล: kongvut/thai-province-data (GitHub)
https://github.com/kongvut/thai-province-data

โครงสร้าง areacode (8 หลัก) ในข้อมูล PM2.5/ผู้ป่วยที่มี:
  areacode = จังหวัด(2) + อำเภอ(2) + ตำบล(2) + หมู่บ้าน(2)
  เช่น 11060115 -> จังหวัด=11, อำเภอ=06, ตำบล=01, หมู่บ้าน=15

district.json ของ kongvut ใช้ "id" 4 หลักแรก = จังหวัด(2)+อำเภอ(2) ตรงกับ
areacode 4 หลักแรกพอดี (ยืนยันแล้ว เช่น id=2001 "เมืองชลบุรี" -> areacode
ที่ขึ้นต้น "2001" คือชลบุรี อำเภอเมือง)

สคริปต์นี้ดึง province.json + district.json มา join กัน แล้ว export เป็น
dim_area.csv (จังหวัด + อำเภอ 2 ระดับ ตามที่ตกลงกันไว้ ไม่ลงถึงตำบล/หมู่บ้าน)
"""

import requests
import pandas as pd

PROVINCE_URL = "https://raw.githubusercontent.com/kongvut/thai-province-data/refs/heads/master/api/latest/province.json"
DISTRICT_URL = "https://raw.githubusercontent.com/kongvut/thai-province-data/refs/heads/master/api/latest/district.json"

print("กำลังดึงข้อมูลจังหวัด...")
province_raw = requests.get(PROVINCE_URL, timeout=30).json()
print(f"  ได้ {len(province_raw)} จังหวัด")

print("กำลังดึงข้อมูลอำเภอ...")
district_raw = requests.get(DISTRICT_URL, timeout=30).json()
print(f"  ได้ {len(district_raw)} อำเภอ")

# --- แปลงเป็น DataFrame ---
df_province = pd.DataFrame(province_raw)[["id", "name_th", "name_en"]]
df_province.columns = ["province_seq_id", "province_name_th", "province_name_en"]

df_district = pd.DataFrame(district_raw)[["id", "name_th", "name_en", "province_id"]]
df_district.columns = ["district_id", "district_name_th", "district_name_en", "province_seq_id"]

# --- ดึงรหัสจังหวัด/อำเภอ 2 หลักจาก district_id (4 หลัก) ---
# district_id เช่น 2001 -> province_code="20", district_code="01"
df_district["district_id_str"] = df_district["district_id"].astype(str).str.zfill(4)
df_district["province_code"] = df_district["district_id_str"].str[:2]
df_district["district_code"] = df_district["district_id_str"].str[2:4]

# --- join กับชื่อจังหวัด ---
dim_area = df_district.merge(df_province, on="province_seq_id", how="left")
dim_area = dim_area[[
    "province_code", "province_name_th", "province_name_en",
    "district_code", "district_name_th", "district_name_en",
]].sort_values(["province_code", "district_code"]).reset_index(drop=True)

print("\nตัวอย่างข้อมูล:")
print(dim_area.head(10))
print(f"\nรวมทั้งหมด: {len(dim_area)} อำเภอ, {dim_area['province_code'].nunique()} จังหวัด")

# --- ตรวจสอบเบื้องต้น: ควรได้ 77 จังหวัด และ ~928 อำเภอ ---
if dim_area["province_code"].nunique() != 77:
    print(f"*** WARNING: ได้ {dim_area['province_code'].nunique()} จังหวัด ควรได้ 77 ***")

dim_area.to_csv("dim_area.csv", index=False, encoding="utf-8-sig")
print("\nSaved -> dim_area.csv")

# --- ตัวอย่างการใช้งาน: join กับ areacode จากข้อมูลผู้ป่วย ---
print("\n=== ตัวอย่างการ join กับ areacode ===")
# สมมติมี df ที่มีคอลัมน์ areacode (8 หลัก) เช่น pm25_disease_monthly
example = pd.DataFrame({"areacode": ["11060115", "20010100", "50010203"]})
example["areacode_str"] = example["areacode"].astype(str).str.zfill(8)
example["province_code"] = example["areacode_str"].str[:2]
example["district_code"] = example["areacode_str"].str[2:4]

example = example.merge(dim_area, on=["province_code", "district_code"], how="left")
print(example)