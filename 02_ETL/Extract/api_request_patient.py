def fetch_monthly(year_be: str, province: str, offset: int = 0, limit: int = 1000,
                   max_retries: int = 5):
    payload = {
        "tableName": TABLE_NAME,
        "year": year_be,
        "province": province,
        "type": "json",
        "offset": offset,
        "limit": limit,
    }
    for attempt in range(1, max_retries + 1):
        resp = requests.post(API_URL, headers=HEADERS, json=payload, timeout=30)
        if resp.status_code == 429:
            wait = (2 ** attempt) + random.uniform(0, 1)
            print(f"    [429] retry {attempt}/{max_retries} in {wait:.1f}s")
            time.sleep(wait)
            continue
        resp.raise_for_status()
        return resp.json()
    raise RuntimeError(f"Failed after {max_retries} retries: year={year_be} province={province}")


def fetch_all_pages(year_be: str, province: str):
    all_rows = []
    offset = 0
    limit = 1000
    while True:
        result = fetch_monthly(year_be, province, offset=offset, limit=limit)
        rows = result.get("data", [])
        total = int(result.get("total", 0))
        all_rows.extend(rows)
        offset += limit
        if offset >= total or not rows:
            break
        time.sleep(1.5)
    return all_rows


